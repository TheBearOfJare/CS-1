public class Chaos {

    private boolean death;
    private int pennies;


    public void printDeath() {
        System.out.println(death);
    }

    public void printPennies() {
        System.out.println(pennies);
    }

    public Chaos(boolean death, int pennies) {
        this.death = death;
        this.pennies = pennies;
    } 





}